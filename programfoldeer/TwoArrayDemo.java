package programfoldeer;

public class TwoArrayDemo {
    public static void main(String[] args) {
        
    
    int arr[][]={{11,3,44},{33,77,88},{55,99,0}};
    for(int i=0;i<3;i++){
        for(int j=0;j<3;j++){
            System.out.print("  "+arr[i][j]);
        }
        System.out.println();

        ///row wise sum
    }
  }
}
